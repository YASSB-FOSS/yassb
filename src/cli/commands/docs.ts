import { readFileSync } from 'fs';
import { resolve } from 'path';
import { DIAGNOSTIC_CODES } from '../../diagnostics/diagnostics';
import type { ParsedArgs } from '../args';

/**
 * `yassb docs [topic] [--list]`: prints `docs/guide.md` (shipped with the package), or one of its sections.
 * Topics are the `## ` headings of the guide; `yassb docs diagnostics` lists the diagnostic codes.
 *
 * @feature cli.docs
 * @summary yassb docs [topic]: prints the guide shipped with the package (docs/guide.md).
 * @usage yassb docs   yassb docs renderers   yassb docs diagnostics   yassb docs --list   yassb docs features [id]
 * @options --list: list topics; topic: a section of the guide (by slug or words of its title); features [id]: the feature catalogue, the checklist of what documentation must cover; --json: the catalogue as JSON.
 * @rules Works offline in every project; the diagnostics topic also lists every diagnostic code.
 * @errors none
 * @status stable
 * @since 2.0.0
 * @related behaviour.diagnostics
 */
export function docsCommand(args: ParsedArgs): number {
  const docs = resolve(__dirname, '..', '..', '..', 'docs');
  // Feature markers (<!-- feature: id -->) are for the catalogue check, not for readers.
  const guide = readFileSync(resolve(docs, 'guide.md'), 'utf8').replace(/^<!--\s*features?:[^>]*-->\n\n?/gm, '');
  const sections = splitSections(guide);
  const topic = args.positionals[0];

  if (topic === 'features')
    return printFeatures(resolve(docs, 'features.json'), args.positionals[1], args.flags.json === true);

  if (args.flags.list === true || topic === 'list') {
    console.log('Topics (yassb docs <topic>):');
    sections.forEach(section => console.log(`  ${section.slug.padEnd(22)} ${section.title}`));
    console.log(`  ${'features'.padEnd(22)} Catalogue of every feature (yassb docs features [id] [--json])`);
    return 0;
  }

  if (!topic) {
    console.log(guide);
    return 0;
  }

  const wanted = topic.toLowerCase();
  const exact = sections.filter(section => section.slug === wanted);
  const matches = exact.length ? exact : sections.filter(section => section.slug.includes(wanted) || section.title.toLowerCase().includes(wanted));
  if (!matches.length) {
    console.error(`No topic "${topic}". Run \`yassb docs --list\`.`);
    return 1;
  }
  console.log(matches.map(section => section.text).join('\n\n'));
  if (matches.some(section => section.slug === 'diagnostics')) {
    console.log('\nCodes:\n');
    for (const [code, description] of Object.entries(DIAGNOSTIC_CODES))
      console.log(`  ${code.padEnd(36)} ${description}`);
  }
  return 0;
}

interface Section {
  title: string;
  slug: string;
  text: string;
}

function splitSections(markdown: string): Array<Section> {
  const sections: Array<Section> = [];
  const parts = markdown.split(/^(?=## )/m);
  for (const part of parts) {
    const match = /^## (.+)$/m.exec(part);
    if (!match || !part.startsWith('## '))
      continue;
    const title = match[1].trim();
    sections.push({ title, slug: title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''), text: part.trim() });
  }
  return sections;
}

interface CatalogueFeature {
  id: string;
  kind: string;
  summary: string;
  usage: string;
  options: string;
  rules: string;
  errors: Array<string>;
  status: string;
  since: string;
  related: Array<string>;
  source: { file: string; line: number; symbol: string };
  parts: Array<{ file: string; line: number; symbol: string }>;
}

/**
 * `yassb docs features [id] [--json]`: the feature catalogue (docs/features.json, generated by the build of
 * yassb from the `@feature` tags of its sources). It is the checklist of what documentation must cover.
 */
function printFeatures(file: string, id: string | undefined, json: boolean): number {
  const catalogue = JSON.parse(readFileSync(file, 'utf8')) as { version: string; features: Array<CatalogueFeature> };
  const wanted = id ? catalogue.features.filter(feature => feature.id === id || feature.id.startsWith(`${id}.`)) : catalogue.features;
  if (!wanted.length) {
    console.error(`No feature "${id}". Run \`yassb docs features\` for the list.`);
    return 1;
  }
  if (json) {
    console.log(JSON.stringify(id ? wanted : catalogue, null, 2));
    return 0;
  }
  if (!id || wanted.length > 1) {
    console.log(`${wanted.length} feature(s) of yassb-web ${catalogue.version}. Details: yassb docs features <id>; all: --json.\n`);
    const kinds = [...new Set(wanted.map(feature => feature.kind))];
    for (const kind of kinds) {
      const list = wanted.filter(feature => feature.kind === kind);
      console.log(`${kind} (${list.length})`);
      for (const feature of list)
        console.log(`  ${feature.id.padEnd(36)} ${feature.summary}${feature.status === 'stable' ? '' : ` [${feature.status}]`}`);
      console.log('');
    }
    return 0;
  }
  const feature = wanted[0];
  console.log([
    `${feature.id}  (${feature.kind}, ${feature.status}, since ${feature.since})`,
    '',
    feature.summary,
    '',
    `Usage:    ${feature.usage}`,
    `Options:  ${feature.options}`,
    `Rules:    ${feature.rules}`,
    `Errors:   ${feature.errors.length ? feature.errors.join(', ') : 'none'}`,
    `Related:  ${feature.related.length ? feature.related.join(', ') : 'none'}`,
    `Source:   ${feature.source.file}:${feature.source.line} (${feature.source.symbol})${feature.parts.length ? `; also ${feature.parts.map(part => part.symbol).join(', ')}` : ''}`
  ].join('\n'));
  return 0;
}
