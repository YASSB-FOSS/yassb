import { readFileSync, writeFileSync } from 'fs';
import { resolve } from 'path';
import { WORKING_DIR } from '../config/working-dir.constant';
import { report } from '../diagnostics/diagnostics';
import { locate, sourceFileOf } from '../diagnostics/source-location';
import { Translator } from '../i18n/translator.class';
import { ListFiles } from '../tools/file-system-helpers/list-files.class';
import { FrontMatterHandler } from '../tools/front-matter/front-matter-handler.class';
import type { YassbConfig } from '../yassb';
import { DirectivesParser } from './directives-parser.class';
import { TemplateToHtmlFiles } from './pages-generator/template-to-html-files.class';

/**
 * Processes every HTML page already in `out` (or `out/<lang>`): directives, then translation.
 * Called once per language. Pages were copied there by `copyPages`, or generated by `generate-from-files`.
 */
export class FilesContentInjector {

  /** Translator of the language being processed (undefined for single-language sites). */
  public translator?: Translator;

  constructor(
    private config: YassbConfig
  ) { }

  public make(lang?: string): void {
    if (lang)
      this.translator = new Translator(WORKING_DIR.i18n, lang, { allowHtml: this.config.i18n?.allowHtml });
    const dest = lang ? resolve(WORKING_DIR.out, lang) : WORKING_DIR.out;
    const htmlFiles = new ListFiles(dest, file => file.endsWith('.html') || file.endsWith('.htm')).init();
    htmlFiles.forEach(file => this.processFile(file, lang));
  }

  /**
   * Directives → front matter stored for post processing → translation → file overwritten in `out`.
   */
  private processFile(file: string, lang?: string): void {
    let fileContents = new DirectivesParser(file, readFileSync(file, 'utf8'), lang as string, this.config).inject();

    FrontMatterHandler.set(file, DirectivesParser.frontMatterData);

    this.reportLeftovers(file, fileContents);

    if (this.translator)
      fileContents = this.translator.processHtml(fileContents, sourceFileOf(file));
    writeFileSync(file, fileContents);
  }

  /**
   * Directives still present after processing mean that content is missing from the page.
   * Problems already reported for the same directive (e.g. a missing data source) are not repeated.
   */
  private reportLeftovers(file: string, html: string): void {
    const patterns: Array<RegExp> = [
      DirectivesParser.regex,
      /<!--\s*create-from-data-source\s*=\s*".+\..+"\s*-->/g,
      /<!--\s*public-file-list\s*=\s*".+"\s* renderer\s*=\s*".+"\s*-->/g,
      /{{\s*url-to\s*=\s*".*?"\s*\s*}}/g,
      TemplateToHtmlFiles.regex
    ];
    for (const directive of this.config.customDirectives || [])
      if (directive && directive.regex instanceof RegExp)
        patterns.push(new RegExp(directive.regex.source, directive.regex.flags.includes('g') ? directive.regex.flags : `${directive.regex.flags}g`));

    for (const pattern of patterns)
      for (const leftover of html.match(pattern) || []) {
        if (leftover === '{{ url-to="myExampleUrl" }}')
          continue;
        report({
          level: 'warning',
          code: 'DIRECTIVE_UNPROCESSED',
          ...locate(file, leftover),
          directive: leftover,
          message: `\`${leftover}\` was not processed: its content is missing from the page.`
        });
      }
  }

}
